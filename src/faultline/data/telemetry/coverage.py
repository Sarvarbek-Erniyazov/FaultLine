# ranges
# -------------------------------------------------------------------------------------


def ranges_rows(
    values: pd.Series, bounds: tuple[float, float] | None, codes: Sequence[float]
) -> dict[str, object]:
    """Describe one channel's values at one source.

    Args:
        values: Every ingested value, nulls included.
        bounds: The configured ``(min, max)``, if any.
        codes: The configured sentinel values.

    Returns:
        Count, quantiles, the repeated tail values, sentinel hits and out-of-bound count.
    """
    numeric = pd.to_numeric(values, errors="coerce").dropna()
    if numeric.empty:
        return {"n": 0}
    q = numeric.quantile(list(QUANTILES)).to_numpy()
    low, high = numeric.quantile(0.001), numeric.quantile(0.999)
    tails = pd.concat([numeric[numeric <= low], numeric[numeric >= high]]).round(2)
    repeated = tails.value_counts()
    repeated = repeated[repeated >= 10].head(4)
    hit = np.zeros(len(numeric), dtype=bool)
    for code in codes:
        hit |= np.isclose(numeric.to_numpy(dtype=float), code, rtol=0.0, atol=SENTINEL_TOLERANCE)
    kept = numeric[~hit]
    outside = int(((kept < bounds[0]) | (kept > bounds[1])).sum()) if bounds is not None else 0
    return {
        "n": int(len(numeric)),
        "min": float(numeric.min()),
        **{f"p{x * 100:g}": float(v) for x, v in zip(QUANTILES, q, strict=True)},
        "max": float(numeric.max()),
        "repeated tail values": ", ".join(f"{k:g} x{v:,}" for k, v in repeated.items()) or "-",
        "sentinel values removed": int(hit.sum()),
        "outside bounds": outside,
    }


def inspect_ranges(
    paths: ProjectPaths, config: TelemetryPipelineConfig, config_path: Path, sources: Sequence[str]
) -> Path:
    """Write the ranges report for the given sources.

    Args:
        paths: Resolved project paths.
        config: The configuration whose sentinels and bounds are applied.
        config_path: Where it was read from.
        sources: Sources to measure.

    Returns:
        The report path.
    """
    parts = [
        _header(
            "Value ranges before any bound",
            config_path,
            paths.repo_root,
            "faultline inspect ranges",
        ),
        "\nEvery ingested value, before sentinels and bounds. `repeated tail values` lists "
        "values at or beyond p0.1 and p99.9 that occur at least 10 times: a sentinel shows "
        "up there as one exact value, many times. The last two columns are what the "
        "configuration's sentinel list and bounds remove.\n",
    ]
    for source in sources:
        files = parquet_files(ingest_dir(paths, source))
        if not files:
            continue
        frame = pd.concat([pd.read_parquet(p) for p in files], ignore_index=True, sort=False)
        bounds = config.bounds_for(source)
        codes = config.clean.sentinels.get(source, {})
        rows: list[tuple[object, ...]] = []
        for channel in config.channels:
            if channel not in frame.columns:
                rows.append((channel, "absent", *[""] * 13))
                continue
            spec = bounds.get(channel)
            described = ranges_rows(
                frame[channel],
                (spec.min, spec.max) if spec is not None else None,
                codes.get(channel, []),
            )
            if described["n"] == 0:
                rows.append((channel, 0, *[""] * 13))
                continue
            rows.append(
                (
                    channel,
                    described["n"],
                    described["min"],
                    *(described[f"p{x * 100:g}"] for x in QUANTILES),
                    described["max"],
                    f"[{spec.min:g}, {spec.max:g}]" if spec is not None else "-",
                    described["repeated tail values"],
                    described["sentinel values removed"],
                    described["outside bounds"],
                )
            )
        parts.append(
            section(
                f"{source} ({len(frame):,} rows)",
                table(
                    [
                        "channel",
                        "n",
                        "min",
                        *(f"p{x * 100:g}" for x in QUANTILES),
                        "max",
                        "bounds",
                        "repeated tail values",
                        "sentinels removed",
                        "outside bounds",
                    ],
                    rows,
                ),
            )
        )
    destination = paths.data_reports_dir / f"ranges_{_stamp()}.md"
    destination.write_text("".join(parts), encoding="utf-8")
    logger.info("wrote %s", destination)
    return destination


