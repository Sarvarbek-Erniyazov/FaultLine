def gap_runs(missing: np.ndarray) -> np.ndarray:
    """Lengths of the runs of ``True`` in a boolean array.

    Args:
        missing: ``True`` where a value is missing.

    Returns:
        The length of every run, in order.
    """
    if missing.size == 0:
        return np.zeros(0, dtype=np.int64)
    padded = np.r_[False, missing, False].astype(np.int8)
    edges = np.flatnonzero(np.diff(padded))
    return (edges[1::2] - edges[0::2]).astype(np.int64)


@dataclass
class ChannelTally:
    """One channel's missingness at one site."""

    grid_steps: int = 0
    grid_present: int = 0
    final_rows: int = 0
    final_before: int = 0
    final_after: int = 0
    imputed: int = 0
    gaps: Counter[int] = field(default_factory=Counter)


@dataclass
class SiteTally:
    """One site's missingness."""

    channels: dict[str, ChannelTally] = field(default_factory=dict)
    presence_grid: Counter[int] = field(default_factory=Counter)
    presence_final: Counter[int] = field(default_factory=Counter)
    grid_steps: int = 0
    final_rows: int = 0
    by_year: dict[int, dict[str, list[int]]] = field(default_factory=dict)


def tally_grid(frame: pd.DataFrame, core: Sequence[str], site: SiteTally) -> None:
    """Accumulate one cleaned turbine-year: coverage, gaps, presence per step, per year."""
    site.grid_steps += len(frame)
    present = np.zeros(len(frame), dtype=np.int64)
    years = pd.to_datetime(frame["timestamp_utc"], utc=True).dt.year.to_numpy()
    for channel in core:
        tally = site.channels.setdefault(channel, ChannelTally())
        tally.grid_steps += len(frame)
        values = (
            frame[channel] if channel in frame.columns else pd.Series(np.nan, index=frame.index)
        )
        notna = values.notna().to_numpy()
        tally.grid_present += int(notna.sum())
        tally.gaps.update(gap_runs(~notna).tolist())
        present += notna
        for year in np.unique(years):
            here = years == year
            counts = site.by_year.setdefault(int(year), {}).setdefault(channel, [0, 0])
            counts[0] += int(here.sum())
            counts[1] += int((notna & here).sum())
    site.presence_grid.update(
        {k: int(v) for k, v in enumerate(np.bincount(present, minlength=len(core) + 1))}
    )


def tally_final(frame: pd.DataFrame, core: Sequence[str], site: SiteTally) -> None:
    """Accumulate one final turbine-year: coverage before and after imputation."""
    site.final_rows += len(frame)
    present = np.zeros(len(frame), dtype=np.int64)
    for channel in core:
        tally = site.channels.setdefault(channel, ChannelTally())
        tally.final_rows += len(frame)
        if channel not in frame.columns:
            continue
        notna = frame[channel].notna().to_numpy()
        mask = f"{channel}{IMPUTED_SUFFIX}"
        imputed = (
            frame[mask].fillna(False).to_numpy(dtype=bool)
            if mask in frame.columns
            else np.zeros(len(frame), dtype=bool)
        )
        tally.final_after += int(notna.sum())
        tally.final_before += int((notna & ~imputed).sum())
        tally.imputed += int(imputed.sum())
        present += notna
    site.presence_final.update(
        {k: int(v) for k, v in enumerate(np.bincount(present, minlength=len(core) + 1))}
    )


def _share(part: int, whole: int, digits: int = 1) -> str:
    return f"{part / whole * 100:.{digits}f}%" if whole else "n/a"


def render_missingness(
    sites: dict[str, SiteTally], core: Sequence[str], header: str, held_out: str | None
) -> str:
    """Render the missingness report.

    Args:
        sites: The tallies per source.
        core: Core channels, in canonical order.
        header: The report header.
        held_out: The held-out source, whose per-year table is printed.

    Returns:
        A Markdown document.
    """
    parts = [
        header,
        "\n`clean grid` is every step of the cleaned grid, gaps included, after sentinels and "
        "bounds. `final` is the rows that survive filtering -- segments of at least a day, a "
        "long gap ending one -- with short gaps imputed and flagged. `before` counts measured "
        "values, `after` measured plus imputed. A channel a site does not publish reads 0%.\n",
    ]
    rows = []
    for source, site in sites.items():
        for channel in core:
            t = site.channels.get(channel, ChannelTally())
            rows.append(
                (
                    source,
                    channel,
                    _share(t.grid_present, t.grid_steps),
                    _share(t.final_before, t.final_rows),
                    _share(t.final_after, t.final_rows),
                    _share(t.imputed, t.final_rows, digits=3),
                )
            )
    parts.append(
        section(
            "Non-null share per site and core channel, before and after imputation",
            table(
                [
                    "site",
                    "channel",
                    "clean grid",
                    "final, before imputation",
                    "final, after imputation",
                    "imputed steps",
                ],
                rows,
            ),
        )
    )
    gap_rows = []
    for source, site in sites.items():
        for channel in core:
            gaps = site.channels.get(channel, ChannelTally()).gaps
            missing = sum(length * n for length, n in gaps.items())
            lengths = np.repeat(np.array(list(gaps), dtype=np.int64), list(gaps.values()))
            buckets = [
                _share(sum(length * n for length, n in gaps.items() if lo <= length <= hi), missing)
                for lo, hi, _ in GAP_BUCKETS
            ]
            gap_rows.append(
                (
                    source,
                    channel,
                    int(sum(gaps.values())),
                    missing,
                    int(np.median(lengths)) if lengths.size else 0,
                    int(np.percentile(lengths, 90)) if lengths.size else 0,
                    int(lengths.max()) if lengths.size else 0,
                    *buckets,
                )
            )
    parts.append(
        section(
            "Gap lengths on the clean grid",
            "A gap is a run of consecutive missing steps within one turbine-year. The bucket "
            "columns give the share of the missing steps that lie in gaps of that length. "
            "Short gaps (up to `max_impute_steps`) are imputed; a gap of `segment_break_steps` "
            "or more ends a segment.\n\n"
            + table(
                [
                    "site",
                    "channel",
                    "gaps",
                    "missing steps",
                    "median length",
                    "p90 length",
                    "longest",
                    *(label for _, _, label in GAP_BUCKETS),
                ],
                gap_rows,
            ),
        )
    )
    width = len(core) + 1
    presence_rows = []
    for source, site in sites.items():
        for name, counts, total in (
            ("clean grid", site.presence_grid, site.grid_steps),
            ("final, after imputation", site.presence_final, site.final_rows),
        ):
            presence_rows.append(
                (source, name, *(_share(counts.get(k, 0), total) for k in range(width)))
            )
    parts.append(
        section(
            "Core channels present in the same 10-minute step",
            f"Share of steps with exactly k of the {len(core)} core channels non-null.\n\n"
            + table(["site", "rows", *(str(k) for k in range(width))], presence_rows),
        )
    )
    if held_out and held_out in sites:
        site = sites[held_out]
        # Years with at least a day of grid: moving interval-end labels to interval start
        # leaves one-row files in the year before each staged year.
        years = sorted(
            y for y, counts in site.by_year.items() if counts.get(core[0], [0, 0])[0] >= 144
        )
        total = sum(counts.get(core[0], [0, 0])[0] for counts in site.by_year.values())
        body = kv_table(
            {
                f"{year} share of the held-out grid": _share(
                    site.by_year[year].get(core[0], [0, 0])[0], total
                )
                for year in years
            }
        )
        body += "\n" + table(
            ["channel", *(str(y) for y in years)],
            [
                (
                    channel,
                    *(
                        _share(
                            site.by_year[y].get(channel, [0, 0])[1],
                            site.by_year[y].get(channel, [0, 0])[0],
                        )
                        for y in years
                    ),
                )
                for channel in core
            ],
        )
        parts.append(
            section(
                f"{held_out}: each core channel per year (clean grid)",
                "Wind direction is core -- the provider's lookup describes it and the 2023 "
                "export carries it -- but the 2019 export does not. Whatever the model reads "
                "at the held-out site, it reads without wind direction in one of its two "
                "years.\n\n" + body,
            )
        )
    return "".join(parts)


def inspect_missingness(
    paths: ProjectPaths,
    config: TelemetryPipelineConfig,
    config_path: Path,
    sources: Sequence[str],
    held_out: str | None = "hill_of_towie",
) -> Path:
    """Write the missingness report from the cleaned and final tables.

    Args:
        paths: Resolved project paths.
        config: The configuration the tables were produced under.
        config_path: Where it was read from.
        sources: Sources to measure.
        held_out: The held-out source, whose per-year table is printed.

    Returns:
        The report path.
    """
    core = list(config.core_channels) or list(config.channels)
    sites: dict[str, SiteTally] = {}
    for source in sources:
        site = SiteTally()
        for path in parquet_files(stage_source_dir(paths, "cleaned", source)):
            tally_grid(pd.read_parquet(path), core, site)
        for path in parquet_files(stage_source_dir(paths, "final", source)):
            tally_final(pd.read_parquet(path), core, site)
        if site.grid_steps:
            sites[source] = site
    header = _header(
        "Missingness per site and core channel",
        config_path,
        paths.repo_root,
        "faultline inspect missingness",
    )
    destination = paths.data_reports_dir / f"missingness_{_stamp()}.md"
    destination.write_text(render_missingness(sites, core, header, held_out), encoding="utf-8")
    logger.info("wrote %s", destination)
    return destination
