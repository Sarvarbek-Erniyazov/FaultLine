"""Value ranges and missingness, measured per site and channel (M1a step 8).

Two tracked reports, each generated from the staged data by one command:

* ``faultline inspect ranges`` reads every *ingested* value, before any bound, and gives
  per source and channel the percentiles from p0.01 to p99.99, the values that repeat in
  the extreme tails (a sentinel shows up as one exact value, many times), and what a
  configuration's sentinel list and bounds remove. It is the evidence behind the bounds
  in ``telemetry_v2.yaml``.
* ``faultline inspect missingness`` reads the *cleaned* grid and the *final* tables and
  answers the questions serialization, context length and model size are chosen from:
  per site and core channel, the non-null share before and after imputation and the
  imputed share; the length of the gaps; how many core channels are present in the same
  10-minute step; and, at the held-out site, each core channel per year -- wind direction
  is core but absent from the 2019 export.

Every figure is accumulated turbine-year by turbine-year, so memory stays at one file.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Sequence
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd

from faultline.data.common.report import kv_table, section, table
from faultline.data.telemetry.clean import SENTINEL_TOLERANCE
from faultline.data.telemetry.pipeline import (
    TelemetryPipelineConfig,
    ingest_dir,
    parquet_files,
    stage_source_dir,
)
from faultline.data.telemetry.schemas import IMPUTED_SUFFIX
from faultline.logging_utils import get_logger
from faultline.paths import ProjectPaths
from faultline.runs import git_sha

logger = get_logger(__name__)

#: Quantiles of the ranges report.
QUANTILES: tuple[float, ...] = (0.0001, 0.001, 0.01, 0.5, 0.99, 0.999, 0.9999)

#: Gap-length buckets, in steps: (lowest, highest, label).
GAP_BUCKETS: tuple[tuple[int, int, str], ...] = (
    (1, 1, "1 step"),
    (2, 3, "2-3"),
    (4, 5, "4-5"),
    (6, 35, "6-35 (to 6 h)"),
    (36, 143, "36-143 (to 1 day)"),
    (144, 1007, "144-1007 (to 1 week)"),
    (1008, 10**9, ">= 1 week"),
)


def _stamp() -> str:
    return datetime.now(tz=UTC).strftime("%Y%m%d")


def _header(title: str, config_path: Path, repo_root: Path, command: str) -> str:
    return f"# {title}\n\n" + kv_table(
        {
            "config": config_path.as_posix(),
            "generated (UTC)": datetime.now(tz=UTC).isoformat(timespec="seconds"),
            "git_sha": git_sha(repo_root),
            "generated by": command,
        }
    )


